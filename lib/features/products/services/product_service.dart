import 'package:dio/dio.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:mini_shop_app/core/errors/app_exception.dart';
import 'package:mini_shop_app/core/network/dio_provider.dart';
import 'package:mini_shop_app/features/products/models/product.dart';

final productServiceProvider = Provider<ProductService>(
  (ref) => ProductService(dio: ref.read(dioProvider)),
);

class ProductService {
  final Dio _dio;
  ProductService({required this._dio});

  Future<List<Product>> fetchProducts() async {
    final res = await _dio.get('/products.json');

    if (res.data == null) return [];

    final data = res.data as Map<String, dynamic>;
    final List<Product> loadedProducts = [];
    data.forEach((prodId, prodData) {
      loadedProducts.add(
        Product(
          id: prodId,
          title: prodData['title'] ?? '',
          description: prodData['description'] ?? '',
          price: (prodData['price'] as num?)?.toDouble() ?? 0.0,
          imageUrl: prodData['imageUrl'] ?? '',
          sellerId: prodData['sellerId'] ?? '',
        ),
      );
    });
    return loadedProducts;
  }

  Future<String> addProduct(Product product, token) async {
    final res = await _dio.post(
      '/products.json',
      data: {
        'title': product.title,
        'description': product.description,
        'imageUrl': product.imageUrl,
        'price': product.price,
        'sellerId': product.sellerId,
      },
    );
    // Return the new ID generated by Firebase
    return res.data['name'];
  }

  Future<void> toggleFavoriteStatus(String id, bool isFavorite, token) async {
    final res = await _dio.patch(
      '/products/$id.json',
      data: {'isFavorite': isFavorite},
    );
    if ((res.statusCode ?? 0) >= 400) {
      throw AppException("Oops, Could not add product to favorites!");
    }
  }

  Future<void> updateProduct(Product product) async {
    final res = await _dio.patch(
      '/products/${product.id}.json',
      data: {
        'title': product.title,
        'description': product.description,
        'imageUrl': product.imageUrl,
        'price': product.price,
      },
    );
    if ((res.statusCode ?? 0) >= 400)
      throw AppException("Could not update product");
  }

  Future<void> deleteProduct(String id) async {
    final response = await _dio.delete('/products/$id.json');
    if ((response.statusCode ?? 0) >= 500) {
      throw AppException("Could not delete product");
    }
  }
}

import 'dart:convert';

import 'package:flutter_dotenv/flutter_dotenv.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:mini_shop_app/core/errors/exceptions.dart';
import 'package:mini_shop_app/features/products/models/product.dart';
import 'package:http/http.dart' as http;

final productServiceProvider = Provider<ProductService>(
  (ref) => ProductService(),
);

class ProductService {
  String get baseUrl => dotenv.env['FIREBASE_DB_URL']!;

  Future<List<Product>> fetchProducts() async {
    final res = await http.get(Uri.https(baseUrl, 'products.json'));
    final decoded = json.decode(res.body) as Map<String, dynamic>?;

    if (decoded == null) return [];

    final List<Product> loadedProducts = [];
    decoded.forEach((prodId, prodData) {
      loadedProducts.add(
        Product(
          id: prodId,
          title: prodData['title'] ?? '',
          description: prodData['description'] ?? '',
          price: (prodData['price'] as num?)?.toDouble() ?? 0.0,
          imageUrl: prodData['imageUrl'] ?? '',
          isFavorite: prodData['isFavorite'] ?? false,
          sellerId: prodData['sellerId'] ?? '',
        ),
      );
    });
    return loadedProducts;
  }

  Future<String> addProduct(Product product, token) async {
    final res = await http.post(
      Uri.https(baseUrl, 'products.json', {'auth': token}),
      body: json.encode({
        'title': product.title,
        'description': product.description,
        'imageUrl': product.imageUrl,
        'price': product.price,
        'isFavorite': product.isFavorite,
        'sellerId': product.sellerId,
      }),
    );
    // Return the new ID generated by Firebase
    return json.decode(res.body)['name'];
  }

  Future<void> toggleFavoriteStatus(String id, bool isFavorite) async {
    final res = await http.patch(
      Uri.https(baseUrl, 'products/$id.json'),
      body: json.encode({'isFavorite': isFavorite}),
    );
    if (res.statusCode >= 400) {
      throw HttpException("Oops, Could not add product to favorites!");
    }
  }

  Future<void> updateProduct(Product product) async {
    final res = await http.patch(
      Uri.https(baseUrl, 'products/${product.id}.json'),
      body: json.encode({
        'title': product.title,
        'description': product.description,
        'imageUrl': product.imageUrl,
        'price': product.price,
        'isFavorite': product.isFavorite,
      }),
    );
    if (res.statusCode >= 400) throw HttpException("Could not update product");
  }

  Future<void> deleteProduct(String id) async {
    final response = await http.delete(Uri.https(baseUrl, 'products/$id.json'));
    if (response.statusCode >= 500) {
      throw HttpException("Could not delete product");
    }
  }
}
